#!/usr/bin/env python3
"""Make a loader header with a game's CMOS defaults from its MiSTer MRA (the
inline hex <part> of 1024 bytes).  Only the low nibbles matter (the CMOS
RAM is 4 bits wide), so two go in each byte, first one high.

  gen_cmos.py "Robotron 2084.mra" cmos_robotron.h
"""
import re, sys

mra = open(sys.argv[1]).read()
blocks = re.findall(r'<part>\s*([0-9A-Fa-f\s]+?)\s*</part>', mra)
data = bytes.fromhex(''.join(max(blocks, key=len).split()))
assert len(data) == 1024, len(data)
packed = bytes(((data[i] & 15) << 4) | (data[i + 1] & 15) for i in range(0, 1024, 2))
with open(sys.argv[2], 'w') as f:
    f.write('/* CMOS defaults from the MiSTer MRA "%s" (generated by gen_cmos.py):\n'
            '   1024 nibbles, two per byte, first one high. */\n' % sys.argv[1].split('/')[-1])
    f.write('static const unsigned char cmos_default[512] = {\n')
    for i in range(0, 512, 16):
        f.write('    ' + ','.join('0x%02x' % b for b in packed[i:i + 16]) + ',\n')
    f.write('};\n')
